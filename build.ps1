# Builds the Hijri Date Picker PCF control and packages it as an UNMANAGED solution
# that imports into Dynamics 365 CE 9.1 on-premises.
#
#   .\build.ps1                      # organization base language English (1033)
#   .\build.ps1 -BaseLanguage 1025   # organization base language Arabic (1025)
#
# Output: .\HijriCalendar_1_0_0_0_unmanaged.zip

param(
    [int]$BaseLanguage = 1033
)

$ErrorActionPreference = "Stop"
$root = $PSScriptRoot

Push-Location "$root\HijriDatePicker"
try {
    if (-not (Test-Path "node_modules")) { npm install }
} finally { Pop-Location }

Push-Location "$root\Solution"
try {
    dotnet build -c Release
    if ($LASTEXITCODE -ne 0) { throw "dotnet build failed" }
} finally { Pop-Location }

$source = "$root\Solution\bin\Release\Solution.zip"
$target = "$root\HijriCalendar_1_0_0_0_unmanaged.zip"
Copy-Item $source $target -Force

Add-Type -AssemblyName System.IO.Compression
Add-Type -AssemblyName System.IO.Compression.FileSystem

# Rewrites one text entry of the zip in place (entry names keep their forward slashes)
function Edit-ZipEntry($zip, [string]$pattern, [scriptblock]$transform) {
    $entry = $zip.Entries | Where-Object { $_.FullName -like $pattern } | Select-Object -First 1
    if (-not $entry) { throw "Entry not found: $pattern" }
    $reader = New-Object IO.StreamReader($entry.Open())
    $text = $reader.ReadToEnd()
    $reader.Close()

    $text = & $transform $text

    $name = $entry.FullName
    $entry.Delete()
    $writer = New-Object IO.StreamWriter($zip.CreateEntry($name).Open(), (New-Object Text.UTF8Encoding $false))
    $writer.Write($text)
    $writer.Close()
}

$zip = [IO.Compression.ZipFile]::Open($target, [IO.Compression.ZipArchiveMode]::Update)
try {
    # Newer pac/pcf-scripts versions emit manifest items that the 9.1 on-prem schema does not know
    # (api-version, <external-service-usage>, <feature-usage/>, <built-by>). Strip them.
    Edit-ZipEntry $zip "Controls/*/ControlManifest.xml" {
        param($xml)
        $xml = $xml -replace '\s+api-version="[^"]*"', ''
        $xml = $xml -replace '\s*<external-service-usage[^>]*/>', ''
        $xml = $xml -replace '(?s)\s*<external-service-usage[^>]*>.*?</external-service-usage>', ''
        $xml = $xml -replace '\s*<feature-usage\s*/>', ''
        $xml -replace '\s*<built-by[^>]*/>', ''
    }

    # pac marks solutions as generated by Dynamics 365 online ("CrmLive"), which on-prem refuses to import.
    # The solution's base language must also match the organization's base language.
    Edit-ZipEntry $zip "solution.xml" {
        param($xml)
        $xml = $xml -replace 'generatedBy="[^"]*"', 'generatedBy="OnPremise"'
        if ($BaseLanguage -ne 1033) { $xml = $xml -replace 'languagecode="1033"', "languagecode=`"$BaseLanguage`"" }
        $xml
    }
    if ($BaseLanguage -ne 1033) {
        Edit-ZipEntry $zip "customizations.xml" { param($xml) $xml -replace '<Language>1033</Language>', "<Language>$BaseLanguage</Language>" }
    }
} finally {
    $zip.Dispose()
}

Write-Host ""
Write-Host "Unmanaged solution ready (base language $BaseLanguage): $target" -ForegroundColor Green
